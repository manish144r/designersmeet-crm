def main():
    print("Building DesignersMeet mockups…")
    for filename, title, active, builder, crumbs, chromeless in SCREEN_DEFS:
        body = builder()
        html = page(title, active, body, crumbs=crumbs, chromeless=chromeless)
        write(SCREENS / filename, html)

    # Index gallery
    idx_html = page("Mockup gallery", "", gallery_body(), crumbs=[], chromeless=True)
    write(ROOT / "index.html", idx_html.replace('../shared/styles.css', 'shared/styles.css'))
