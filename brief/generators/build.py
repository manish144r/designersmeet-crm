#!/usr/bin/env python3
"""DesignersMeet mockup generator.

Emits 15 high-fidelity HTML mockups + gallery + spec sheet.
All chrome (sidebar, topbar) is generated by this script so all screens
stay in lockstep. Each screen-specific function returns its page body only.
"""
