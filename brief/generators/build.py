def topbar(crumbs: list[str] = None, right_extra: str = "") -> str:
    crumbs = crumbs or []
    crumb_html = ""
    if crumbs:
        parts = []
        for i, c in enumerate(crumbs):
            last = (i == len(crumbs) - 1)
            color = "text-slate-900 font-medium" if last else "text-slate-500"
            parts.append(f'<span class="{color}">{c}</span>')
        crumb_html = (
            '<nav class="flex items-center gap-2 text-[13px]">'
            + '<i data-lucide="chevron-right" class="icon-sm text-slate-300"></i>'.join(parts)
            + '</nav>'
        )

    return f"""
    <header class="app-topbar">
      {crumb_html}
      <div class="dm-search flex-1 max-w-[480px] ml-auto mr-auto">
        <i data-lucide="search"></i>
        <input type="text" placeholder="Search contacts, projects, vendors…" />
        <span class="absolute right-2 top-1/2 -translate-y-1/2"><kbd class="kbd">⌘K</kbd></span>
      </div>
      <div class="flex items-center gap-1 ml-auto">
        {right_extra}
        <button class="btn-icon" title="Help"><i data-lucide="circle-help" class="icon-sm"></i></button>
        <button class="btn-icon relative" title="Notifications">
          <i data-lucide="bell" class="icon-sm"></i>
          <span class="absolute top-1 right-1 w-1.5 h-1.5 rounded-full bg-indigo-600"></span>
        </button>
        <div class="w-px h-6 bg-slate-200 mx-1"></div>
        <button class="flex items-center gap-2 px-2 py-1 rounded-md hover:bg-slate-50">
          <div class="avatar avatar-a avatar-sm">MS</div>
          <i data-lucide="chevron-down" class="icon-sm text-slate-400"></i>
        </button>
      </div>
    </header>
    """

def page(title: str, active_nav: str, body: str, crumbs=None, topbar_right="", chromeless=False) -> str:
    """Wrap a screen body in the full app shell."""
    head = f"""<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8" />
  <meta name="viewport" content="width=1440, initial-scale=1" />
  <title>{title} · DesignersMeet</title>
  <script src="https://cdn.tailwindcss.com"></script>
  <link rel="stylesheet" href="../shared/styles.css" />
  <script src="https://unpkg.com/lucide@latest/dist/umd/lucide.js"></script>
</head>
<body class="bg-white text-slate-900 antialiased">
"""
    if chromeless:
        shell = body
    else:
        shell = f"""
  <div class="flex h-screen overflow-hidden">
    {sidebar(active_nav)}
    <div class="flex-1 flex flex-col overflow-hidden min-w-0">
      {topbar(crumbs, topbar_right)}
      <main class="flex-1 overflow-auto bg-white">
        {body}
      </main>
    </div>
  </div>
"""
    return head + shell + """
  <script>if (window.lucide) lucide.createIcons();</script>
</body>
</html>
"""

# ───────────────────────── Helpers ──────────────────────────

def avatar(initials: str, variant: str = "a", size: str = "") -> str:
    cls = f"avatar avatar-{variant}"
    if size: cls += f" avatar-{size}"
    return f'<div class="{cls}">{initials}</div>'


def write(path: Path, content: str):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")
    print(f"  wrote {path.relative_to(ROOT)}")


